        line.strokeWidth = 3 * u
        when (kind) {
            REMOTE -> {
                fill.color = Color.parseColor("#2E4F66"); cv.drawRoundRect(RectF(20 * u, 8 * u, 44 * u, 56 * u), 10 * u, 10 * u, fill)
